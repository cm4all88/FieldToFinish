using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text.RegularExpressions;

namespace FieldCodes.Contours
{
    /// <summary>One elevation to contour: the exact value and the text it was typed as.</summary>
    public sealed class ContourElevation
    {
        /// <summary>The elevation, parsed straight from <see cref="Text"/> -- never rounded.</summary>
        public double Value { get; private set; }

        /// <summary>The elevation as typed (12.60 stays 12.60), used for labels and messages.</summary>
        public string Text { get; private set; }

        public ContourElevation(double value, string text)
        {
            Value = value;
            Text = text;
        }

        /// <summary>The identity used to find an earlier run's contours at this elevation.</summary>
        public string Key { get { return ContourKeys.Elevation(Value); } }

        public override string ToString() { return Text; }
    }

    /// <summary>What the elevation prompt came back with.</summary>
    public sealed class ElevationList
    {
        public List<ContourElevation> Elevations { get; private set; }

        /// <summary>Input that could not be read. Any problem means nothing is drawn.</summary>
        public List<string> Problems { get; private set; }

        /// <summary>Things worth saying that are not errors (duplicates merged).</summary>
        public List<string> Notes { get; private set; }

        public ElevationList()
        {
            Elevations = new List<ContourElevation>();
            Problems = new List<string>();
            Notes = new List<string>();
        }

        public bool Ok { get { return Problems.Count == 0 && Elevations.Count > 0; } }
    }

    /// <summary>
    /// Reads the elevations typed at FTFCONTOUR: one (12.6), a list (12.6, 13.0, 13.5 --
    /// commas, semicolons or spaces), or a run (10 to 14 by 0.5). Each value is parsed from
    /// its own text with the invariant culture, so 12.6 is exactly the double 12.6 whether it
    /// was typed or generated by a run; nothing is rounded to a display precision. The same
    /// value typed twice (13 and 13.0) is drawn once.
    /// </summary>
    public static class ContourElevations
    {
        /// <summary>More than this in one go is almost certainly a typo in a run's step.</summary>
        public const int MaxCount = 500;

        private static readonly Regex NumberPattern = new Regex(
            @"^[+-]?(?:[0-9]+(?:\.[0-9]*)?|\.[0-9]+)$", RegexOptions.CultureInvariant);

        private static readonly Regex RunPattern = new Regex(
            @"^(?<from>\S+)\s+(?:to|thru|through)\s+(?<to>\S+)(?:\s+(?:by|step|every)\s+(?<step>\S+))?$",
            RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);

        public static ElevationList Parse(string input)
        {
            var result = new ElevationList();
            var text = (input ?? string.Empty).Trim();
            if (text.Length == 0)
            {
                result.Problems.Add("Type at least one elevation, e.g. 12.6 or 12.6, 13.0, 13.5.");
                return result;
            }

            var seen = new Dictionary<double, ContourElevation>();
            foreach (var rawItem in text.Split(new[] { ',', ';' }, StringSplitOptions.None))
            {
                var item = Regex.Replace(rawItem.Trim(), @"\s+", " ");
                if (item.Length == 0) continue;   // a stray or trailing comma is harmless

                var run = RunPattern.Match(item);
                if (run.Success)
                {
                    AddRun(run, item, result, seen);
                    continue;
                }

                foreach (var token in item.Split(' '))
                    AddOne(token, result, seen);
            }

            if (result.Elevations.Count > MaxCount)
                result.Problems.Add(string.Format(CultureInfo.InvariantCulture,
                    "{0} elevations is more than the {1} FTFCONTOUR draws in one go; check the step.",
                    result.Elevations.Count, MaxCount));

            if (result.Problems.Count == 0 && result.Elevations.Count == 0)
                result.Problems.Add("Type at least one elevation.");

            return result;
        }

        private static void AddOne(string token, ElevationList result, Dictionary<double, ContourElevation> seen)
        {
            string normal;
            double value;
            if (!TryNumber(token, out normal, out value))
            {
                result.Problems.Add(Describe(token));
                return;
            }
            Add(new ContourElevation(value, normal), result, seen);
        }

        private static void AddRun(Match run, string item, ElevationList result,
                                   Dictionary<double, ContourElevation> seen)
        {
            var fromText = run.Groups["from"].Value;
            var toText = run.Groups["to"].Value;
            var stepText = run.Groups["step"].Success ? run.Groups["step"].Value : null;

            decimal from, to, step;
            if (!TryDecimal(fromText, out from)) { result.Problems.Add(Describe(fromText)); return; }
            if (!TryDecimal(toText, out to)) { result.Problems.Add(Describe(toText)); return; }
            if (stepText == null)
            {
                result.Problems.Add(string.Format(CultureInfo.InvariantCulture,
                    "\"{0}\": say the step too, e.g. {1} to {2} by 1.", item, fromText, toText));
                return;
            }
            if (!TryDecimal(stepText, out step)) { result.Problems.Add(Describe(stepText)); return; }

            step = Math.Abs(step);
            if (step == 0m)
            {
                result.Problems.Add(string.Format(CultureInfo.InvariantCulture,
                    "\"{0}\": the step cannot be zero.", item));
                return;
            }

            // Counted in decimal so 10 to 11 by 0.1 lands on 11 exactly, with no drift.
            var span = Math.Abs(to - from);
            var steps = decimal.Floor(span / step);
            if (steps + 1 > MaxCount)
            {
                result.Problems.Add(string.Format(CultureInfo.InvariantCulture,
                    "\"{0}\" makes {1} elevations; FTFCONTOUR draws at most {2} in one go.",
                    item, steps + 1, MaxCount));
                return;
            }

            var places = Math.Max(Scale(fromText), Math.Max(Scale(toText), Scale(stepText)));
            var direction = to >= from ? 1m : -1m;
            for (var i = 0m; i <= steps; i++)
            {
                var v = from + direction * step * i;
                var vText = v.ToString("F" + places.ToString(CultureInfo.InvariantCulture),
                                       CultureInfo.InvariantCulture);
                string normal;
                double value;
                if (TryNumber(vText, out normal, out value))
                    Add(new ContourElevation(value, normal), result, seen);
            }
        }

        private static void Add(ContourElevation elevation, ElevationList result,
                                Dictionary<double, ContourElevation> seen)
        {
            ContourElevation first;
            if (seen.TryGetValue(elevation.Value, out first))
            {
                if (first.Text == elevation.Text)
                    result.Notes.Add(string.Format(CultureInfo.InvariantCulture,
                        "{0} was given more than once; drawn once.", elevation.Text));
                else
                    result.Notes.Add(string.Format(CultureInfo.InvariantCulture,
                        "{0} and {1} are the same elevation; drawn once, as {0}.",
                        first.Text, elevation.Text));
                return;
            }
            seen.Add(elevation.Value, elevation);
            result.Elevations.Add(elevation);
        }

        /// <summary>Reads one number exactly as typed. Leading + dropped, .5 written 0.5.</summary>
        public static bool TryNumber(string token, out string normal, out double value)
        {
            normal = null;
            value = 0;
            var t = (token ?? string.Empty).Trim();
            if (!NumberPattern.IsMatch(t)) return false;

            if (t.StartsWith("+", StringComparison.Ordinal)) t = t.Substring(1);
            var negative = t.StartsWith("-", StringComparison.Ordinal);
            var body = negative ? t.Substring(1) : t;
            if (body.StartsWith(".", StringComparison.Ordinal)) body = "0" + body;
            if (body.EndsWith(".", StringComparison.Ordinal)) body = body.Substring(0, body.Length - 1);
            t = (negative ? "-" : string.Empty) + body;

            if (!double.TryParse(t, NumberStyles.AllowLeadingSign | NumberStyles.AllowDecimalPoint,
                                 CultureInfo.InvariantCulture, out value))
                return false;
            if (double.IsNaN(value) || double.IsInfinity(value)) return false;
            if (value == 0) { value = 0; t = t.TrimStart('-'); }   // no -0 contours

            normal = t;
            return true;
        }

        private static bool TryDecimal(string token, out decimal value)
        {
            value = 0m;
            var t = (token ?? string.Empty).Trim();
            if (!NumberPattern.IsMatch(t)) return false;
            return decimal.TryParse(t, NumberStyles.AllowLeadingSign | NumberStyles.AllowDecimalPoint,
                                    CultureInfo.InvariantCulture, out value);
        }

        private static int Scale(string token)
        {
            var dot = (token ?? string.Empty).IndexOf('.');
            return dot < 0 ? 0 : token.Length - dot - 1;
        }

        private static string Describe(string token)
        {
            return string.Format(CultureInfo.InvariantCulture,
                "\"{0}\" is not an elevation. Use numbers like 12.6 (a point for decimals), " +
                "separated by commas or spaces, or a run like 10 to 14 by 0.5.", token);
        }
    }

    /// <summary>Identities stamped on FTF contours so a re-run finds its own work.</summary>
    public static class ContourKeys
    {
        /// <summary>Round-trip text of the exact value: 12.6 and 12.60 share a key, 12.6 and
        /// 12.600001 do not.</summary>
        public static string Elevation(double value)
        {
            if (value == 0) value = 0;   // -0 and 0 are one contour
            return value.ToString("R", CultureInfo.InvariantCulture);
        }

        /// <summary>The owner key for one surface and elevation: surface handle @ elevation.</summary>
        public static string Owner(string surfaceHandle, double elevation)
        {
            return (surfaceHandle ?? string.Empty) + "@" + Elevation(elevation);
        }

        /// <summary>Splits an owner key back apart; false when it is not one.</summary>
        public static bool TryRead(string key, out string surfaceHandle, out double elevation)
        {
            surfaceHandle = null;
            elevation = 0;
            if (string.IsNullOrEmpty(key)) return false;
            var at = key.LastIndexOf('@');
            if (at <= 0 || at == key.Length - 1) return false;
            surfaceHandle = key.Substring(0, at);
            return double.TryParse(key.Substring(at + 1), NumberStyles.Float,
                                   CultureInfo.InvariantCulture, out elevation);
        }
    }
}
