using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;
using System.Text.RegularExpressions;

// Writes a placeholder for every public Civil 3D type the hand-written stand-ins do not declare,
// so the compile checks see every name AeccDbMgd.dll and AecBaseMgd.dll declare. See README.md.
//
//   CivilApiNames [-C3D2024 <install root>] [-Out <file>] [-Prefix <namespace>]... [<assembly>...]

var c3d = @"C:\Program Files\Autodesk\AutoCAD 2024";
string? output = null;
var prefixes = new List<string>();
var assemblies = new List<string>();
for (var i = 0; i < args.Length; i++)
{
    var a = args[i];
    string Next() => i + 1 < args.Length ? args[++i] : throw new ArgumentException(a + " needs a value.");
    if (a.Equals("-C3D2024", StringComparison.OrdinalIgnoreCase)) c3d = Next();
    else if (a.Equals("-Out", StringComparison.OrdinalIgnoreCase)) output = Next();
    else if (a.Equals("-Prefix", StringComparison.OrdinalIgnoreCase)) prefixes.Add(Next());
    else if (a is "-h" or "-?" or "/?" or "-Help")
    {
        Console.WriteLine("CivilApiNames [-C3D2024 <install root>] [-Out <file>] [-Prefix <namespace>]... [<assembly>...]");
        return 0;
    }
    else assemblies.Add(a);
}
if (prefixes.Count == 0) prefixes.AddRange(new[] { "Autodesk.Civil", "Autodesk.Aec" });
if (assemblies.Count == 0)
    assemblies.AddRange(new[] { Path.Combine(c3d, "C3D", "AeccDbMgd.dll"), Path.Combine(c3d, "AecBaseMgd.dll") });

var repo = FindRepo(AppContext.BaseDirectory) ?? FindRepo(Directory.GetCurrentDirectory());
if (repo == null) return Fail("Run this from inside the FieldToFinish working copy.");
var stubs = Path.Combine(repo, "tests", "CadCompileCheck", "Stubs");
output ??= Path.Combine(stubs, "CivilApiNames.g.cs");

var missing = assemblies.Where(f => !File.Exists(f)).ToList();
if (missing.Count > 0)
    return Fail("Not found: " + string.Join(", ", missing) + ". Pass -C3D2024 \"<install root>\" (the folder that holds acad.exe).");

// Names the hand-written stand-ins declare already: a second declaration would not compile.
var handWritten = new HashSet<string>(StringComparer.Ordinal);
foreach (var file in new[] { "Civil.cs", "CivilShadows.cs" }.Select(f => Path.Combine(stubs, f)).Where(File.Exists))
    foreach (var name in Declared(File.ReadAllText(file))) handWritten.Add(name);

var byNamespace = new SortedDictionary<string, SortedSet<string>>(StringComparer.Ordinal);
var sources = new List<string>();
foreach (var path in assemblies)
{
    using var stream = File.OpenRead(path);
    using var pe = new PEReader(stream);
    if (!pe.HasMetadata) return Fail(path + " has no .NET metadata.");
    var md = pe.GetMetadataReader();
    var def = md.GetAssemblyDefinition();
    sources.Add(string.Format("{0} {1}", md.GetString(def.Name), def.Version));
    foreach (var handle in md.TypeDefinitions)
    {
        var type = md.GetTypeDefinition(handle);
        // Top-level public types only: a nested type is never named bare from outside.
        if ((type.Attributes & TypeAttributes.VisibilityMask) != TypeAttributes.Public) continue;
        var ns = md.GetString(type.Namespace);
        if (!prefixes.Any(p => ns == p || ns.StartsWith(p + ".", StringComparison.Ordinal))) continue;
        var name = md.GetString(type.Name);
        // C++/CLI writes template instances (Value<bool>) and compiler types (<Module>) that C#
        // cannot name, so they cannot clash with anything the plugin writes.
        if (!Regex.IsMatch(name, @"^[A-Za-z_][A-Za-z0-9_]*(`[0-9]+)?$")) continue;
        if (!byNamespace.TryGetValue(ns, out var set)) byNamespace[ns] = set = new SortedSet<string>(StringComparer.Ordinal);
        set.Add(name);
    }
}

var sb = new StringBuilder();
sb.AppendLine("// <auto-generated>");
sb.AppendLine("// Written by tools/CivilApiNames from " + string.Join(", ", sources) + ". Do not edit; run it again.");
sb.AppendLine("// A placeholder for every public type of those assemblies that Civil.cs and CivilShadows.cs do not");
sb.AppendLine("// declare, so a bare name Civil 3D shares with AutoCAD or .NET is ambiguous (CS0104) in the compile");
sb.AppendLine("// checks as it is in the Windows build. Names only: no member, no behaviour, nothing of Autodesk's.");
sb.AppendLine("// </auto-generated>");
sb.AppendLine("#pragma warning disable 1591");
var written = 0;
foreach (var pair in byNamespace)
{
    var names = pair.Value.Where(n => !handWritten.Contains(pair.Key + "." + Plain(n))).ToList();
    if (names.Count == 0) continue;
    sb.AppendLine();
    sb.AppendLine("namespace " + pair.Key);
    sb.AppendLine("{");
    foreach (var name in names)
    {
        var plain = Plain(name);
        var arity = name.Length > plain.Length ? int.Parse(name.Substring(plain.Length + 1)) : 0;
        var generic = arity == 0 ? "" : "<" + string.Join(", ", Enumerable.Range(1, arity).Select(n => "T" + n)) + ">";
        sb.AppendFormat("    public sealed class {0}{1} {{ private {0}() {{ }} }}", Identifier(plain), generic).AppendLine();
        written++;
    }
    sb.AppendLine("}");
}

Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(output))!);
File.WriteAllText(output, sb.ToString().Replace("\r\n", "\n"), new UTF8Encoding(false));
Console.WriteLine("Read " + string.Join(", ", sources) + ".");
Console.WriteLine("Wrote " + written + " placeholders (" + handWritten.Count + " names are hand-written stand-ins) to " + output + ".");
Console.WriteLine("Next: dotnet build tests/CadCompileCheck, tests/RealApiCompileCheck and tests/SmokeHarnessCompileCheck, then commit the file.");
return 0;

static string Plain(string metadataName)
{
    var tick = metadataName.IndexOf('`');
    return tick < 0 ? metadataName : metadataName.Substring(0, tick);
}

static string Identifier(string name)
{
    var keywords = new HashSet<string>(StringComparer.Ordinal)
    {
        "abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class", "const",
        "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event", "explicit", "extern",
        "false", "finally", "fixed", "float", "for", "foreach", "goto", "if", "implicit", "in", "int", "interface",
        "internal", "is", "lock", "long", "namespace", "new", "null", "object", "operator", "out", "override", "params",
        "private", "protected", "public", "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc",
        "static", "string", "struct", "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked",
        "unsafe", "ushort", "using", "virtual", "void", "volatile", "while",
    };
    return keywords.Contains(name) ? "@" + name : name;
}

static IEnumerable<string> Declared(string text)
{
    string? ns = null;
    foreach (var raw in text.Split('\n'))
    {
        var line = raw;
        var comment = line.IndexOf("//", StringComparison.Ordinal);
        if (comment >= 0) line = line.Substring(0, comment);
        var n = Regex.Match(line, @"^\s*namespace\s+([\w.]+)");
        if (n.Success) { ns = n.Groups[1].Value; continue; }
        if (ns == null) continue;
        foreach (Match t in Regex.Matches(line, @"\b(?:class|struct|enum|interface)\s+(\w+)"))
            yield return ns + "." + t.Groups[1].Value;
    }
}

static string? FindRepo(string start)
{
    for (var dir = new DirectoryInfo(start); dir != null; dir = dir.Parent)
        if (File.Exists(Path.Combine(dir.FullName, "FieldToFinish.sln"))) return dir.FullName;
    return null;
}

static int Fail(string message)
{
    Console.Error.WriteLine("CivilApiNames: " + message);
    return 1;
}
